-- TicketLoop target schema (M0 draft).
--
-- This is the design, not a migration. From M2 on, each module's Alembic migration builds
-- its own tables from this file. Explanations are in docs/database-design.md.
--
-- Check that it is valid SQL against the compose Postgres (uses a scratch database):
--   docker compose exec -T db createdb -U ticketloop schema_check
--   docker compose exec -T db psql -U ticketloop -d schema_check -v ON_ERROR_STOP=1 -q -f - < docs/schema-draft.sql
--   docker compose exec -T db dropdb -U ticketloop schema_check
--
-- Conventions:
--   ids             UUID, generated by Postgres (gen_random_uuid is built in since PG 13)
--   timestamps      TIMESTAMPTZ in UTC; updated_at is set by the application on every write
--   money           BIGINT paise, never float; currency is INR only for now
--   statuses        TEXT + CHECK, not Postgres ENUM types (easier to change in migrations)
--   deletes         rows are never hard-deleted, so foreign keys keep the default RESTRICT
--   names           pk_ primary key, uq_ unique, ix_ index, ck_ check

CREATE EXTENSION IF NOT EXISTS pg_trgm;  -- trigram index for event-name search (M6)


-- ===================================================================== identity (M3)

CREATE TABLE users (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email           TEXT NOT NULL,
    password_hash   TEXT NOT NULL,                   -- Argon2id; never the password
    full_name       TEXT NOT NULL,
    role            TEXT NOT NULL DEFAULT 'USER',
    account_status  TEXT NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_account_status CHECK (account_status IN ('ACTIVE', 'SUSPENDED'))
);

CREATE TABLE refresh_tokens (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id      UUID NOT NULL REFERENCES users (id),
    family_id    UUID NOT NULL,                      -- shared by every token from one login
    token_hash   TEXT NOT NULL,                      -- SHA-256 of the token, never the token
    expires_at   TIMESTAMPTZ NOT NULL,
    revoked_at   TIMESTAMPTZ,
    replaced_by  UUID REFERENCES refresh_tokens (id),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_replaced_means_revoked
        CHECK (replaced_by IS NULL OR revoked_at IS NOT NULL)
);
CREATE INDEX ix_refresh_tokens_family_id ON refresh_tokens (family_id);
CREATE INDEX ix_refresh_tokens_user_id_live ON refresh_tokens (user_id) WHERE revoked_at IS NULL;

CREATE TABLE password_reset_tokens (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id     UUID NOT NULL REFERENCES users (id),
    token_hash  TEXT NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_password_reset_tokens_token_hash UNIQUE (token_hash)
);


-- ===================================================================== catalogue (M4)

CREATE TABLE ticket_providers (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code        TEXT NOT NULL,                       -- 'fakeprovider' now, a real one later
    name        TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_ticket_providers_code UNIQUE (code)
);

CREATE TABLE events (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name         TEXT NOT NULL,
    description  TEXT NOT NULL DEFAULT '',
    category     TEXT NOT NULL,
    venue        TEXT NOT NULL,
    city         TEXT NOT NULL,
    starts_at    TIMESTAMPTZ NOT NULL,
    organizer    TEXT NOT NULL,
    provider_id  UUID NOT NULL REFERENCES ticket_providers (id),
    status       TEXT NOT NULL DEFAULT 'DRAFT',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_events_category CHECK (category IN ('CONCERT', 'SPORTS', 'COLLEGE', 'OTHER')),
    CONSTRAINT ck_events_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CANCELLED', 'COMPLETED'))
);
CREATE INDEX ix_events_status_starts ON events (status, starts_at);
CREATE INDEX ix_events_city ON events (city);
CREATE INDEX ix_events_name_trgm ON events USING gin (name gin_trgm_ops);

CREATE TABLE tickets (
    id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id              UUID NOT NULL REFERENCES events (id),
    original_owner_id     UUID NOT NULL REFERENCES users (id),
    current_owner_id      UUID NOT NULL REFERENCES users (id),  -- changes when a transfer completes
    ticket_category       TEXT NOT NULL,             -- provider's label: 'GENERAL', 'VIP', ...
    seat_details          TEXT,
    original_price_paise  BIGINT NOT NULL,
    purchase_reference    TEXT NOT NULL,             -- private
    provider_reference    TEXT NOT NULL,             -- private: the provider's id for this ticket
    verification_status   TEXT NOT NULL DEFAULT 'PENDING',
    transfer_eligible     BOOLEAN NOT NULL DEFAULT false,
    status                TEXT NOT NULL DEFAULT 'ACTIVE',
    verified_by           UUID REFERENCES users (id),
    verified_at           TIMESTAMPTZ,
    verification_note     TEXT,                      -- the admin's reason, shown to the owner (M4)
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_tickets_event_provider_reference UNIQUE (event_id, provider_reference),
    CONSTRAINT ck_tickets_price CHECK (original_price_paise > 0),
    CONSTRAINT ck_tickets_verification_status
        CHECK (verification_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT ck_tickets_status CHECK (status IN ('ACTIVE', 'VOID'))
);
CREATE INDEX ix_tickets_owner ON tickets (current_owner_id, created_at);
CREATE INDEX ix_tickets_pending_verification ON tickets (created_at)
    WHERE verification_status = 'PENDING';

CREATE TABLE ticket_documents (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ticket_id     UUID NOT NULL REFERENCES tickets (id),
    uploaded_by   UUID NOT NULL REFERENCES users (id),
    storage_key   TEXT NOT NULL,                     -- random object key, never the file name
    content_type  TEXT NOT NULL,
    size_bytes    BIGINT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_ticket_documents_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_ticket_documents_type
        CHECK (content_type IN ('application/pdf', 'image/png', 'image/jpeg')),
    CONSTRAINT ck_ticket_documents_size CHECK (size_bytes BETWEEN 1 AND 5242880)  -- 5 MiB
);
CREATE INDEX ix_ticket_documents_ticket ON ticket_documents (ticket_id);


-- ===================================================================== listings (M5)

CREATE TABLE listings (
    id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ticket_id             UUID NOT NULL REFERENCES tickets (id),
    event_id              UUID NOT NULL REFERENCES events (id),   -- copied from the ticket
    seller_id             UUID NOT NULL REFERENCES users (id),
    asking_price_paise    BIGINT NOT NULL,
    original_price_paise  BIGINT NOT NULL,                        -- copied from the ticket
    status                TEXT NOT NULL DEFAULT 'DRAFT',
    expires_at            TIMESTAMPTZ NOT NULL,      -- defaults to the event start
    reviewed_by           UUID REFERENCES users (id),
    reviewed_at           TIMESTAMPTZ,
    rejection_reason      TEXT,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_listings_status CHECK (status IN (
        'DRAFT', 'PENDING_VERIFICATION', 'ACTIVE', 'RESERVED',
        'SOLD', 'REJECTED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_listings_min_price CHECK (asking_price_paise >= 100),
    CONSTRAINT ck_listings_price_cap CHECK (asking_price_paise <= original_price_paise),
    CONSTRAINT ck_listings_rejection_reason
        CHECK (status <> 'REJECTED' OR rejection_reason IS NOT NULL)
);
-- FR-04 rule 2: one ticket, at most one open listing.
CREATE UNIQUE INDEX uq_listings_one_open_per_ticket ON listings (ticket_id)
    WHERE status IN ('DRAFT', 'PENDING_VERIFICATION', 'ACTIVE', 'RESERVED');
CREATE INDEX ix_listings_event_status ON listings (event_id, status);
CREATE INDEX ix_listings_seller_status ON listings (seller_id, status);
-- Discovery sorts (M6): partial, because only ACTIVE listings are ever searched.
CREATE INDEX ix_listings_active_by_price ON listings (asking_price_paise, id) WHERE status = 'ACTIVE';
CREATE INDEX ix_listings_active_by_created ON listings (created_at, id) WHERE status = 'ACTIVE';
CREATE INDEX ix_listings_active_expiry ON listings (expires_at) WHERE status = 'ACTIVE';
CREATE INDEX ix_listings_review_queue ON listings (created_at) WHERE status = 'PENDING_VERIFICATION';


-- ===================================================================== interests and reservations (M7, M8)

CREATE TABLE interests (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    listing_id  UUID NOT NULL REFERENCES listings (id),
    buyer_id    UUID NOT NULL REFERENCES users (id),
    status      TEXT NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_interests_status
        CHECK (status IN ('ACTIVE', 'SELECTED', 'EXPIRED', 'WITHDRAWN', 'REJECTED'))
);
-- FR-06: one live interest per buyer per listing.
CREATE UNIQUE INDEX uq_interests_one_live_per_buyer ON interests (listing_id, buyer_id)
    WHERE status IN ('ACTIVE', 'SELECTED');
-- First-come-first-served allocation reads this in order.
CREATE INDEX ix_interests_fcfs ON interests (listing_id, created_at, id) WHERE status = 'ACTIVE';
CREATE INDEX ix_interests_buyer ON interests (buyer_id, created_at);

CREATE TABLE reservations (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    listing_id   UUID NOT NULL REFERENCES listings (id),
    buyer_id     UUID NOT NULL REFERENCES users (id),
    interest_id  UUID REFERENCES interests (id),     -- set when allocation picked this buyer
    status       TEXT NOT NULL DEFAULT 'CREATED',
    expires_at   TIMESTAMPTZ NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_reservations_interest UNIQUE (interest_id),
    CONSTRAINT ck_reservations_status CHECK (status IN (
        'CREATED', 'PAYMENT_PENDING', 'CONFIRMED', 'EXPIRED', 'FAILED', 'CANCELLED'))
);
-- The safety net under the conditional UPDATE (M8): one live reservation per listing.
CREATE UNIQUE INDEX uq_reservations_one_live_per_listing ON reservations (listing_id)
    WHERE status IN ('CREATED', 'PAYMENT_PENDING', 'CONFIRMED');
CREATE INDEX ix_reservations_listing_status ON reservations (listing_id, status);
-- The expiry worker's scan.
CREATE INDEX ix_reservations_due ON reservations (expires_at)
    WHERE status IN ('CREATED', 'PAYMENT_PENDING');
CREATE INDEX ix_reservations_buyer ON reservations (buyer_id, created_at);


-- ===================================================================== orders (M9)

CREATE TABLE orders (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    reservation_id   UUID NOT NULL REFERENCES reservations (id),
    listing_id       UUID NOT NULL REFERENCES listings (id),
    buyer_id         UUID NOT NULL REFERENCES users (id),
    seller_id        UUID NOT NULL REFERENCES users (id),
    amount_paise     BIGINT NOT NULL,                -- copied from the listing, never from the client
    currency         CHAR(3) NOT NULL DEFAULT 'INR',
    status           TEXT NOT NULL DEFAULT 'CREATED',
    idempotency_key  TEXT NOT NULL,                  -- kept for tracing; uniqueness lives below
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- The second layer against duplicate orders: one order per reservation.
    CONSTRAINT uq_orders_reservation UNIQUE (reservation_id),
    CONSTRAINT ck_orders_amount CHECK (amount_paise > 0),
    CONSTRAINT ck_orders_currency CHECK (currency = 'INR'),
    CONSTRAINT ck_orders_not_own_listing CHECK (buyer_id <> seller_id),  -- FR-04 rule 4
    CONSTRAINT ck_orders_status CHECK (status IN (
        'CREATED', 'PAYMENT_PENDING', 'PAID', 'TRANSFER_PENDING', 'COMPLETED',
        'PAYMENT_FAILED', 'CANCELLED', 'REFUND_PENDING', 'REFUNDED', 'TRANSFER_FAILED'))
);
CREATE INDEX ix_orders_buyer ON orders (buyer_id, created_at, id);
CREATE INDEX ix_orders_seller ON orders (seller_id, created_at, id);
CREATE INDEX ix_orders_listing ON orders (listing_id);

CREATE TABLE idempotency_keys (
    user_id          UUID NOT NULL REFERENCES users (id),
    key              TEXT NOT NULL,                  -- the client's Idempotency-Key header
    request_method   TEXT NOT NULL,
    request_path     TEXT NOT NULL,
    request_hash     TEXT NOT NULL,                  -- SHA-256 of method, path and canonical body
    response_status  SMALLINT,                       -- NULL until the first request finishes
    response_body    JSONB,
    locked_at        TIMESTAMPTZ,                    -- held during an external call (M10)
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at       TIMESTAMPTZ NOT NULL,           -- created_at + 24 hours
    CONSTRAINT pk_idempotency_keys PRIMARY KEY (user_id, key),
    CONSTRAINT ck_idempotency_keys_length CHECK (length(key) BETWEEN 1 AND 255)
);
CREATE INDEX ix_idempotency_keys_expiry ON idempotency_keys (expires_at);


-- ===================================================================== payments (M10)

CREATE TABLE payments (
    id                       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id                 UUID NOT NULL REFERENCES orders (id),
    provider                 TEXT NOT NULL,
    provider_transaction_id  TEXT,                   -- NULL until the gateway answers
    amount_paise             BIGINT NOT NULL,
    currency                 CHAR(3) NOT NULL DEFAULT 'INR',
    status                   TEXT NOT NULL DEFAULT 'CREATED',
    idempotency_key          TEXT NOT NULL,          -- what we send to the gateway
    provider_response        JSONB,                  -- latest snapshot; full history is in payment_events
    failure_reason           TEXT,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- NULLs count as distinct in a UNIQUE constraint, so many rows may still lack a provider id.
    CONSTRAINT uq_payments_provider_transaction UNIQUE (provider, provider_transaction_id),
    CONSTRAINT uq_payments_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_payments_provider CHECK (provider IN ('fakepay')),  -- 'razorpay' later
    CONSTRAINT ck_payments_amount CHECK (amount_paise > 0),
    CONSTRAINT ck_payments_currency CHECK (currency = 'INR'),
    CONSTRAINT ck_payments_status
        CHECK (status IN ('CREATED', 'PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED'))
);
-- FR-09 rule 4: a payment belongs to one order, and an order has one live payment.
CREATE UNIQUE INDEX uq_payments_one_live_per_order ON payments (order_id)
    WHERE status IN ('CREATED', 'PENDING', 'SUCCEEDED', 'REFUNDED');
CREATE INDEX ix_payments_order ON payments (order_id);
-- Reconciliation's scan for payments stuck before a final state.
CREATE INDEX ix_payments_unresolved ON payments (created_at) WHERE status IN ('CREATED', 'PENDING');

CREATE TABLE payment_events (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    provider           TEXT NOT NULL,
    provider_event_id  TEXT NOT NULL,
    payment_id         UUID REFERENCES payments (id),  -- NULL if it matches no payment we know
    event_type         TEXT NOT NULL,                -- 'payment.succeeded', 'refund.succeeded', ...
    payload            JSONB NOT NULL,               -- the verified body, kept forever
    processing_status  TEXT NOT NULL DEFAULT 'RECEIVED',
    error              TEXT,
    received_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at       TIMESTAMPTZ,
    -- Webhook dedupe: the second delivery of an event cannot insert.
    CONSTRAINT uq_payment_events_provider_event UNIQUE (provider, provider_event_id),
    CONSTRAINT ck_payment_events_processing_status
        CHECK (processing_status IN ('RECEIVED', 'PROCESSED', 'IGNORED', 'FAILED'))
);
CREATE INDEX ix_payment_events_payment ON payment_events (payment_id, received_at);

CREATE TABLE refunds (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    payment_id          UUID NOT NULL REFERENCES payments (id),
    order_id            UUID NOT NULL REFERENCES orders (id),
    amount_paise        BIGINT NOT NULL,
    currency            CHAR(3) NOT NULL DEFAULT 'INR',
    status              TEXT NOT NULL DEFAULT 'REQUESTED',
    reason              TEXT NOT NULL,
    provider_refund_id  TEXT,
    idempotency_key     TEXT NOT NULL,
    requested_by        UUID REFERENCES users (id),  -- NULL when the system asked
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_refunds_provider_refund UNIQUE (provider_refund_id),
    CONSTRAINT uq_refunds_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_refunds_amount CHECK (amount_paise > 0),
    CONSTRAINT ck_refunds_currency CHECK (currency = 'INR'),
    CONSTRAINT ck_refunds_status CHECK (status IN ('REQUESTED', 'PENDING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_refunds_reason
        CHECK (reason IN ('TRANSFER_FAILED', 'DISPUTE', 'ADMIN', 'LATE_PAYMENT'))
);
-- Full refunds only, so at most one live refund per payment.
CREATE UNIQUE INDEX uq_refunds_one_live_per_payment ON refunds (payment_id)
    WHERE status IN ('REQUESTED', 'PENDING', 'SUCCEEDED');

CREATE TABLE reconciliation_runs (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    status         TEXT NOT NULL DEFAULT 'RUNNING',
    started_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at    TIMESTAMPTZ,
    checked_count  INT NOT NULL DEFAULT 0,
    fixed_count    INT NOT NULL DEFAULT 0,
    findings       JSONB NOT NULL DEFAULT '[]',      -- one entry per mismatch and the fix applied
    error          TEXT,
    CONSTRAINT ck_reconciliation_runs_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED'))
);


-- ===================================================================== messaging (M11)

CREATE TABLE outbox_events (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),  -- also the message id consumers dedupe on
    aggregate_type   TEXT NOT NULL,                  -- 'order', 'listing', 'reservation', ...
    aggregate_id     UUID NOT NULL,
    event_type       TEXT NOT NULL,                  -- 'payment.succeeded', ...
    payload          JSONB NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at     TIMESTAMPTZ,                    -- NULL until the broker confirmed it
    retry_count      INT NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error       TEXT
);
-- The relay's scan. Partial, so it stays tiny however many events have been published.
CREATE INDEX ix_outbox_unpublished ON outbox_events (created_at) WHERE published_at IS NULL;

CREATE TABLE processed_events (
    consumer      TEXT NOT NULL,                     -- e.g. 'transfers.start'
    event_id      UUID NOT NULL,                     -- outbox_events.id
    processed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_processed_events PRIMARY KEY (consumer, event_id)
);


-- ===================================================================== transfers and notifications (M12)

CREATE TABLE transfers (
    id                           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id                     UUID NOT NULL REFERENCES orders (id),
    ticket_id                    UUID NOT NULL REFERENCES tickets (id),
    from_user_id                 UUID NOT NULL REFERENCES users (id),
    to_user_id                   UUID NOT NULL REFERENCES users (id),
    provider_id                  UUID NOT NULL REFERENCES ticket_providers (id),
    provider_transfer_reference  TEXT,
    status                       TEXT NOT NULL DEFAULT 'INITIATED',
    attempt_count                INT NOT NULL DEFAULT 0,
    last_error                   TEXT,
    initiated_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at                 TIMESTAMPTZ,
    updated_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_transfers_order UNIQUE (order_id),
    CONSTRAINT uq_transfers_provider_reference UNIQUE (provider_transfer_reference),
    CONSTRAINT ck_transfers_status CHECK (status IN (
        'INITIATED', 'PROCESSING', 'COMPLETED', 'FAILED', 'REQUIRES_MANUAL_REVIEW'))
);
CREATE INDEX ix_transfers_review_queue ON transfers (updated_at) WHERE status = 'REQUIRES_MANUAL_REVIEW';

CREATE TABLE notifications (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id            UUID NOT NULL REFERENCES users (id),
    notification_type  TEXT NOT NULL,
    payload            JSONB NOT NULL,
    source_event_id    UUID,                         -- the outbox event that caused it
    read_at            TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_notifications_event_user UNIQUE (source_event_id, user_id)
);
CREATE INDEX ix_notifications_user ON notifications (user_id, created_at DESC, id DESC);


-- ===================================================================== disputes (M13)

CREATE TABLE disputes (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id         UUID NOT NULL REFERENCES orders (id),
    opened_by        UUID NOT NULL REFERENCES users (id),
    reason           TEXT NOT NULL,
    description      TEXT NOT NULL,
    status           TEXT NOT NULL DEFAULT 'OPEN',
    resolved_by      UUID REFERENCES users (id),
    resolved_at      TIMESTAMPTZ,
    resolution_note  TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_disputes_reason CHECK (reason IN (
        'TICKET_NOT_RECEIVED', 'TICKET_INVALID', 'NOT_AS_DESCRIBED', 'PAYMENT_ISSUE', 'OTHER')),
    CONSTRAINT ck_disputes_status CHECK (status IN (
        'OPEN', 'UNDER_REVIEW', 'RESOLVED_REFUND', 'RESOLVED_RELEASE', 'REJECTED'))
);
CREATE UNIQUE INDEX uq_disputes_one_open_per_order ON disputes (order_id)
    WHERE status IN ('OPEN', 'UNDER_REVIEW');
CREATE INDEX ix_disputes_queue ON disputes (status, created_at);

CREATE TABLE dispute_events (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    dispute_id   UUID NOT NULL REFERENCES disputes (id),
    actor_id     UUID REFERENCES users (id),         -- NULL = the system
    event_type   TEXT NOT NULL,
    from_status  TEXT,
    to_status    TEXT,
    note         TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_dispute_events_type
        CHECK (event_type IN ('OPENED', 'EVIDENCE_ADDED', 'COMMENT', 'STATUS_CHANGED'))
);
CREATE INDEX ix_dispute_events_dispute ON dispute_events (dispute_id, created_at);

CREATE TABLE dispute_evidence (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    dispute_id    UUID NOT NULL REFERENCES disputes (id),
    uploaded_by   UUID NOT NULL REFERENCES users (id),
    storage_key   TEXT NOT NULL,
    content_type  TEXT NOT NULL,
    size_bytes    BIGINT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_dispute_evidence_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_dispute_evidence_type
        CHECK (content_type IN ('application/pdf', 'image/png', 'image/jpeg')),
    CONSTRAINT ck_dispute_evidence_size CHECK (size_bytes BETWEEN 1 AND 5242880)
);
CREATE INDEX ix_dispute_evidence_dispute ON dispute_evidence (dispute_id);


-- ===================================================================== audit (M5)

CREATE TABLE audit_logs (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    actor_id     UUID,                               -- no FK on purpose; NULL = the system
    entity_type  TEXT NOT NULL,                      -- 'listing', 'reservation', 'order', ...
    entity_id    UUID NOT NULL,
    action       TEXT NOT NULL,                      -- 'listing.approved', 'reservation.expired', ...
    request_id   TEXT,                               -- links the row to that request's log lines
    details      JSONB NOT NULL DEFAULT '{}',        -- from_status, to_status, reason, ...
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_logs_entity ON audit_logs (entity_type, entity_id, created_at);
CREATE INDEX ix_audit_logs_actor ON audit_logs (actor_id, created_at);

-- History tables are append-only. The app never updates or deletes them; this trigger makes
-- the database refuse even if a bug or a person tries.
CREATE FUNCTION forbid_update_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END;
$$;

CREATE TRIGGER audit_logs_append_only
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION forbid_update_delete();

CREATE TRIGGER dispute_events_append_only
    BEFORE UPDATE OR DELETE ON dispute_events
    FOR EACH ROW EXECUTE FUNCTION forbid_update_delete();
